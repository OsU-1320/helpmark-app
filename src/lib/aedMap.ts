/**
 * 日本全国AEDマップ（aedm.jp）へのリンク。
 * このアプリに入っているAEDは、東京都のオープンデータ（各区・市が個別に公開しているもの）のうち、一部の地域の分だけ。
 * 全国のAEDは、外部の地図へ案内する（データは取り込まない。利用条件が確認できないため）。
 *
 * aedm.jp は、開いた端末の現在地を、自分で取得して、地図の中心にする（URLで座標を指定する仕組みは無い）。
 * そのため、リンクは、トップを開くだけでよい。位置情報の許可を求められたら、許可すると、近くのAEDが見える。
 */
export const AED_MAP_SITE = 'https://aedm.jp/'

/** 日本全国AEDマップのURL。座標は、使わない（開いた先が、現在地を取得する）。引数は、呼び出し側を変えずに済むよう残してある */
export function aedMapUrl(_coords?: { latitude: number; longitude: number } | null): string {
  return AED_MAP_SITE
}

/** 「近くのAED」として出してよい距離（メートル）。これより遠いものは、近くとは言えないので、出さない */
export const NEAR_AED_MAX_M = 500

/**
 * ボタンの下に出す注記。aedm.jp は、開いた端末の現在地を自分で取得するため、
 * 外部の会社のサイトに位置情報が渡る場合があることを、押す前に伝える。
 */
export const AED_MAP_NOTE = '外部サイト（運営：株式会社アルム）が開きます。位置情報の許可を求められることがあります'
